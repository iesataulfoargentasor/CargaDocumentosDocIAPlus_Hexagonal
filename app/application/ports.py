"""Contratos de salida. El núcleo solo depende de estos puertos y del dominio."""
from typing import Protocol, BinaryIO
from app.domain.document import ValidatedFile
from app.domain.user import Account

class DocumentRepository(Protocol):
    def list_all(self) -> list[dict]: ...
    def get(self, document_id: str) -> dict: ...
    def save(self, document: dict, content: bytes) -> None: ...
    def download(self, document: dict, max_bytes: int) -> bytes: ...

class UserRepository(Protocol):
    def get_active(self, username: str) -> Account | None: ...

class PasswordVerifier(Protocol):
    def verify(self, stored_hash: str | None, password: str) -> bool: ...

class FileValidator(Protocol):
    def validate(self, stream: BinaryIO | None, filename: str, max_bytes: int) -> ValidatedFile: ...
